/* קריאה רגילה — the whole book as a plain ebook, for readers who would rather just read.
   No drawings, no motion beyond the page turn: a title page, a contents page, then every
   piece in book order, each starting on a new page. Turned the way an ebook in Hebrew is
   turned, sideways: tap or click the left side, swipe to the right, ← or space for the next
   page; the right side, ← → reversed, for the previous one. Two pages side by side on a wide
   screen, one on a phone. The text comes from stories/book-text.js (generated by
   tools/booktext.mjs), loaded only when the reader opens. Type size and place are kept. */
(() => {
  const B = window.BOOK;
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const SIZES = [16.5, 18, 19.5, 21, 23];
  const KEY_SIZE = "andati:reader:size", KEY_AT = "andati:reader:at";
  const store = {
    get: k => { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set: (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} }
  };
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
  const CHEV_NEXT = `<svg viewBox="0 0 8 14" aria-hidden="true"><path d="M7 1L1 7l6 6"/></svg>`;
  const CHEV_PREV = `<svg viewBox="0 0 8 14" aria-hidden="true"><path d="M1 1l6 6-6 6"/></svg>`;

  const css = `
.rd { position: fixed; inset: 0; background: var(--paper); z-index: 1;
  display: grid; grid-template-rows: calc(56px + env(safe-area-inset-top, 0px)) 28px minmax(0, 1fr) calc(60px + env(safe-area-inset-bottom, 0px));
  padding-left: var(--gut-l); padding-right: var(--gut-r); touch-action: pinch-zoom; }
.rd-run { grid-row: 2; align-self: center; text-align: center; font-family: var(--f-ui); font-weight: 300; font-size: 12px; letter-spacing: .05em; color: var(--ink-faint);
  white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
.rd-stage { grid-row: 3; position: relative; display: flex; justify-content: center; min-height: 0; padding-top: 2vh; cursor: default; }
.rd-window { height: 100%; overflow: hidden; position: relative; }
.rd-window::after { content: ""; position: absolute; top: 0; bottom: 0; left: 50%; width: 1px; background: var(--mist); display: var(--spine, none); }
.rd-flow { height: 100%; column-fill: auto; orphans: 2; widows: 2;
  font-family: var(--f-body); font-size: var(--rd-size, 19.5px); line-height: 1.85; color: var(--ink); }
.rd-flow.slide { transition: transform .5s cubic-bezier(.6,.05,.25,1); }
.rd-flow p { margin: 0; text-align: justify; text-wrap: pretty; hyphens: none; }
.rd-flow p + p { text-indent: 1.4em; }
.rd-flow p.line, .rd-flow p.said, .rd-flow p.line + p, .rd-flow p.said + p { text-indent: 0; text-align: start; }
.rd-flow p.line, .rd-flow p.said { margin-bottom: .15em; }
.rd-flow p.solo { text-indent: 0; text-align: center; font-family: var(--f-display); padding: .7em 0; }
.rd-flow p.solo + p { text-indent: 0; }
.rd-flow p.thanks { text-indent: 0; text-align: start; font-family: var(--f-display); font-size: 1.5em; margin-top: 1.4em; }
.rd-flow .st { text-align: start; margin: 0 0 1.2em; break-inside: avoid; }
.rd-flow .st + p { text-indent: 0; }
.rd-flow .st span { display: block; }
.rd-flow .rd-time { text-indent: 0; text-align: start; font-family: var(--f-ui); font-weight: 300; font-size: .8em; letter-spacing: .04em; color: var(--ink-soft); margin: 1.2em 0 .3em; direction: ltr; text-align: right; }
.rd-flow .rd-time + p { text-indent: 0; }
.rd-flow .rd-gap { height: 1.6em; }
.rd-flow .rd-row { display: grid; grid-template-columns: 1fr 1fr; gap: 1.2em; break-inside: avoid; }
.rd-flow .rd-row span { min-height: 1.85em; }
.rd-flow .rd-rows { margin-bottom: 1.6em; }
.rd-part { break-before: column; -webkit-column-break-before: always; font-family: var(--f-display); font-weight: 400; font-size: 1.35em; line-height: 1.3; margin: 0 0 1.2em; }
.rd-part.first { break-before: auto; -webkit-column-break-before: auto; }
.rd-sec { break-before: column; -webkit-column-break-before: always; }
.rd-h { padding-top: 12%; margin-bottom: 2.2em; break-inside: avoid; break-after: avoid; }
.rd-h .eyebrow { display: block; }
.rd-h h2 { font-family: var(--f-display); font-weight: 300; font-size: 2.1em; line-height: 1.1; margin: 10px 0 6px; }
.rd-h .sub { font-family: var(--f-ui); font-weight: 300; font-size: .75em; color: var(--ink-soft); letter-spacing: .04em; }
.rd-blank { break-before: column; -webkit-column-break-before: always; height: 1px; }
.rd-title { height: 100%; display: flex; flex-direction: column; justify-content: center; break-after: column; -webkit-column-break-after: always; }
.rd-title h1 { font-family: var(--f-display); font-weight: 300; font-size: 3.4em; line-height: 1; margin: 0 0 .4em; }
.rd-title .by { font-family: var(--f-ui); font-weight: 300; font-size: .85em; letter-spacing: .05em; color: var(--ink-soft); }
.rd-contents h2 { font-family: var(--f-display); font-weight: 300; font-size: 1.6em; margin: 0 0 1em; padding-top: 6%; }
.rd-contents ol, .rd-tocp ol { list-style: none; margin: 0; padding: 0; }
.rd-contents li a, .rd-tocp li a { display: grid; grid-template-columns: minmax(0, 1fr) auto; gap: 12px; align-items: baseline; text-decoration: none; color: var(--ink); cursor: pointer; }
.rd-contents li a { font-size: .82em; line-height: 1.55; padding: .12em 0; }
.rd-contents .s, .rd-tocp .s { font-family: var(--f-ui); font-weight: 300; font-size: .78em; color: var(--ink-soft); margin-inline-start: 6px; }
.rd-contents .n, .rd-tocp .n { font-family: var(--f-mono); font-weight: 300; font-size: .72em; color: var(--ink-faint); font-variant-numeric: tabular-nums; }
.rd-contents li a:hover .t, .rd-tocp li a:hover .t { text-decoration: underline; text-underline-offset: 4px; text-decoration-thickness: 1px; }
.rd-end { break-before: column; -webkit-column-break-before: always; padding-top: 30%; display: grid; gap: 28px; font-family: var(--f-ui); }
.rd-end .mark { width: 40px; height: 1px; background: var(--ink); }
.rd-end nav { display: flex; flex-wrap: wrap; gap: 28px; font-size: 13px; letter-spacing: .08em; }
.rd-end nav a { text-decoration: none; border-bottom: 1px solid var(--hair); padding-bottom: 3px; }

.rd-foot { grid-row: 4; display: grid; grid-template-columns: 1fr auto 1fr; align-items: center; width: min(1040px, 100%); margin: 0 auto;
  padding-bottom: env(safe-area-inset-bottom, 0px); font-family: var(--f-ui); font-weight: 300; font-size: 12px; color: var(--ink-soft); }
.rd-foot button { border: 0; background: none; padding: 10px; cursor: pointer; color: var(--ink-soft); font: inherit; }
.rd-foot button:hover { color: var(--ink); }
.rd-foot button[disabled] { color: var(--hair); cursor: default; }
.rd-foot .open-toc { justify-self: start; letter-spacing: .06em; padding-right: 0; }
.rd-ctrl { display: flex; align-items: center; gap: 10px; }
.rd-ctrl svg { width: 8px; height: 14px; display: block; }
.rd-ctrl path { fill: none; stroke: currentColor; stroke-width: 1.2; }
.rd-count { font-family: var(--f-mono); font-size: 12px; direction: ltr; min-width: 6.5em; text-align: center; }
.rd-size { justify-self: end; display: flex; align-items: baseline; }
.rd-size button { font-family: var(--f-display); padding: 10px 8px; }
.rd-size .sm { font-size: 14px; } .rd-size .lg { font-size: 19px; padding-left: 0; }

.rd-tocp { position: fixed; inset: 0; z-index: 50; background: var(--paper); overflow-y: auto; overscroll-behavior: contain;
  padding: calc(64px + env(safe-area-inset-top, 0px)) var(--gut-r) 10vh var(--gut-l); }
.rd-tocp[hidden] { display: none; }
.rd-tocp .in { max-width: 34rem; margin: 0 auto; }
.rd-tocp .top { display: flex; justify-content: space-between; align-items: baseline; margin-bottom: 4vh; }
.rd-tocp h2 { font-family: var(--f-display); font-weight: 300; font-size: 34px; margin: 0; }
.rd-tocp .close { border: 0; background: none; padding: 6px 0; cursor: pointer; font-family: var(--f-ui); font-weight: 300; font-size: 13px; letter-spacing: .06em; color: var(--ink-soft); }
.rd-tocp li a { font-size: 18px; padding: 9px 0; border-bottom: 1px solid var(--mist); }
.rd-tocp li a.here .t { color: var(--accent); }
.rd-tocp .t { font-family: var(--f-display); }

@media (max-width: 860px) {
  .rd { grid-template-rows: calc(52px + env(safe-area-inset-top, 0px)) 24px minmax(0, 1fr) calc(56px + env(safe-area-inset-bottom, 0px)); }
  .rd-foot { grid-template-columns: auto 1fr auto; }
  .rd-ctrl { justify-self: center; }
}`;

  let active = null;
  function loadText() {
    if (window.BOOK_TEXT) return Promise.resolve(window.BOOK_TEXT);
    return new Promise((ok, fail) => {
      const s = document.createElement("script");
      s.src = "stories/book-text.js";
      s.onload = () => ok(window.BOOK_TEXT); s.onerror = fail;
      document.head.appendChild(s);
    });
  }

  function blockHTML(b, i, k) {
    const at = ` data-k="${k}"`;
    if (b.t === "p") return `<p${b.c ? ` class="${b.c}"` : ""}${at}>${esc(b.x)}</p>`;
    if (b.t === "st") return `<p class="st"${at}>${b.l.map(l => `<span>${l ? esc(l) : "&nbsp;"}</span>`).join("")}</p>`;
    if (b.t === "h") return `<h3 class="rd-part${i === 0 ? " first" : ""}"${at}>${esc(b.x)}</h3>`;
    if (b.t === "time") return `<p class="rd-time"${at}>${esc(b.x)}</p>`;
    if (b.t === "gap") return `<div class="rd-gap"></div>`;
    if (b.t === "cols") return `<div class="rd-rows"${at}>${b.a.map((a, j) => `<div class="rd-row"><span>${esc(a)}</span><span>${esc(b.b[j] || "")}</span></div>`).join("")}</div>`;
    return "";
  }
  const tocList = (secs, cls) => `<ol>${secs.map(s => `<li><a data-go="${s.id}"${cls ? ` class="${cls}"` : ""}><span><span class="t">${esc(s.t)}</span>${s.s ? `<span class="s">${esc(s.s)}</span>` : ""}</span><span class="n" data-n="${s.id}"></span></a></li>`).join("")}</ol>`;

  function bookHTML(secs) {
    return `<div class="rd-title" data-k="title"><h1>ענדתי<br>אושר</h1><div class="by">בועז כץ</div></div>
      <div class="rd-contents" data-k="contents"><h2>תוכן</h2>${tocList(secs)}</div>
      ${secs.map(s => `<section class="rd-sec" data-sec="${s.id}">
        <header class="rd-h" data-k="${s.id}:h"><span class="eyebrow">${esc(s.kind)}</span><h2>${esc(s.t)}</h2>${s.s ? `<div class="sub">${esc(s.s)}</div>` : ""}</header>
        ${s.blocks.length ? s.blocks.map((b, i) => blockHTML(b, i, `${s.id}:${i}`)).join("") : `<div class="rd-blank"></div>`}
      </section>`).join("")}
      <div class="rd-end" data-k="end"><div class="mark"></div><span class="eyebrow">סוף</span><nav><a href="#toc">חזרה לתוכן האתר</a><a href="#">לעמוד הבית</a></nav></div><span class="rd-s"></span>`;
  }

  function mount(root) {
    if (!document.getElementById("rd-css")) {
      const st = document.createElement("style"); st.id = "rd-css"; st.textContent = css;
      document.head.appendChild(st);
    }
    document.documentElement.classList.add("kt-lock");
    root.innerHTML = `<section class="rd" aria-roledescription="ספר">
      <div class="rd-run" aria-hidden="true"></div>
      <div class="rd-stage"><div class="rd-window"><div class="rd-flow"></div></div></div>
      <footer class="rd-foot">
        <button type="button" class="open-toc" aria-haspopup="dialog">קטעים</button>
        <span class="rd-ctrl"><button type="button" class="pv" aria-label="לעמוד הקודם">${CHEV_PREV}</button><span class="rd-count" aria-live="polite"></span><button type="button" class="nx" aria-label="לעמוד הבא">${CHEV_NEXT}</button></span>
        <span class="rd-size"><button type="button" class="sm" aria-label="אותיות קטנות יותר">א</button><button type="button" class="lg" aria-label="אותיות גדולות יותר">א</button></span>
      </footer>
      <div class="rd-tocp" role="dialog" aria-label="קטעים" hidden><div class="in"><div class="top"><h2>קטעים</h2><button type="button" class="close">סגירה</button></div><div class="list"></div></div></div>
    </section>`;
    const rd = root.querySelector(".rd"), stage = rd.querySelector(".rd-stage"), win = rd.querySelector(".rd-window"), flow = rd.querySelector(".rd-flow");
    const count = rd.querySelector(".rd-count"), run = rd.querySelector(".rd-run"), tocp = rd.querySelector(".rd-tocp");
    const bar = document.getElementById("progress");
    let secs = [], pw = 0, pg = 0, per = 1, cols = 1, spreads = 1, page = 0, marks = [], secCol = {}, alive = true;
    let size = Math.max(0, Math.min(SIZES.length - 1, parseInt(store.get(KEY_SIZE) ?? (innerWidth <= 860 ? 1 : 2), 10)));
    let at = store.get(KEY_AT);
    count.textContent = "…";

    function layout() {
      const sw = stage.clientWidth, narrow = innerWidth <= 860;
      per = !narrow && sw >= 1000 ? 2 : 1;
      pg = per === 2 ? 96 : 60;
      pw = Math.floor(per === 2 ? Math.min(500, (sw - 120 - pg) / 2) : Math.min(narrow ? 560 : 600, sw - (narrow ? 8 : 160)));
      const ww = per * pw + (per - 1) * pg;
      win.style.width = ww + "px";
      rd.style.setProperty("--spine", per === 2 ? "block" : "none");
      rd.style.setProperty("--rd-size", SIZES[size] + "px");
      flow.classList.remove("slide");
      Object.assign(flow.style, { width: ww + "px", columnWidth: pw + "px", columnCount: per, columnGap: pg + "px", transform: "none" });
      const R = flow.getBoundingClientRect().right, step = pw + pg;
      const colAt = r => Math.max(0, Math.round((R - r.right) / step));
      const colOf = el => { const r = el.getClientRects()[0]; return r ? colAt(r) : 0; };
      const s = flow.querySelector(".rd-s").getClientRects();
      cols = colAt(s[s.length - 1]) + 1;
      spreads = Math.ceil(cols / per);
      marks = [...flow.querySelectorAll("[data-k]")].map(el => ({ k: el.dataset.k, col: colOf(el) }));
      secCol = {};
      secs.forEach(x => { const m = marks.find(m => m.k === x.id + ":h"); secCol[x.id] = m ? m.col : 0; });
      rd.querySelectorAll("[data-n]").forEach(n => n.textContent = secCol[n.dataset.n] + 1);
      const m = at && marks.find(m => m.k === at);
      go(m ? Math.floor(m.col / per) : Math.min(page, spreads - 1), false);
      flow.offsetWidth;
      flow.classList.add("slide");
    }
    function go(n, animate = true) {
      n = Math.max(0, Math.min(spreads - 1, n));
      page = n;
      if (!animate || reduced) flow.classList.remove("slide");
      flow.style.transform = `translateX(${n * per * (pw + pg)}px)`;
      if (!animate || reduced) { flow.offsetWidth; if (!reduced) flow.classList.add("slide"); }
      const c0 = n * per, c1 = Math.min(cols, c0 + per);
      count.textContent = c1 - c0 > 1 ? `${c0 + 1}–${c1} / ${cols}` : `${c0 + 1} / ${cols}`;
      if (bar) bar.style.transform = `scaleX(${spreads > 1 ? n / (spreads - 1) : 1})`;
      rd.querySelector(".rd-ctrl .pv").disabled = n === 0;
      rd.querySelector(".rd-ctrl .nx").disabled = n === spreads - 1;
      if (n === spreads - 1 && spreads > 1 && B.reached) B.reached();
      // the running head names the piece on the page, and the place is remembered by the first block in view
      const first = marks.find(m => m.col >= c0) || marks[marks.length - 1];
      if (animate && first) { at = first.k; store.set(KEY_AT, at); }
      const cur = [...secs].reverse().find(x => secCol[x.id] <= c1 - 1);
      run.textContent = c0 < 2 || !cur ? "ענדתי אושר" : `${cur.t}${cur.s ? " · " + cur.s : ""}`;
      rd.querySelectorAll(".rd-tocp a").forEach(a => a.classList.toggle("here", !!cur && a.dataset.go === cur.id));
    }
    const next = () => go(page + 1), prev = () => go(page - 1);
    const goSec = id => { if (id in secCol) { at = id + ":h"; store.set(KEY_AT, at); go(Math.floor(secCol[id] / per), false); } }; // a jump, not a turn

    /* input: a sideways book, as ebooks in Hebrew turn */
    const onKey = e => {
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      if (!tocp.hidden) { if (e.key === "Escape") closeToc(); return; }
      if (["ArrowLeft", "PageDown", " "].includes(e.key) && !e.shiftKey) { e.preventDefault(); next(); }
      else if (["ArrowRight", "PageUp"].includes(e.key) || (e.key === " " && e.shiftKey)) { e.preventDefault(); prev(); }
      else if (e.key === "Home") { e.preventDefault(); go(0); }
      else if (e.key === "End") { e.preventDefault(); go(spreads - 1); }
    };
    let acc = 0, lock = 0;
    const onWheel = e => {
      e.preventDefault();
      const now = performance.now();
      if (now < lock) return;
      acc += Math.abs(e.deltaY) > Math.abs(e.deltaX) ? e.deltaY : -e.deltaX;
      if (Math.abs(acc) > 40) { acc > 0 ? next() : prev(); acc = 0; lock = now + 550; }
    };
    let tx = null, ty = 0, swiped = 0;
    const onStart = e => { tx = e.touches[0].clientX; ty = e.touches[0].clientY; };
    const onEnd = e => {
      if (tx === null) return;
      const dx = e.changedTouches[0].clientX - tx, dy = e.changedTouches[0].clientY - ty;
      tx = null;
      if (Math.abs(dx) > 40 && Math.abs(dx) > Math.abs(dy) * 1.2) { dx > 0 ? next() : prev(); swiped = performance.now(); }
    };
    stage.addEventListener("click", e => {
      const g = e.target.closest("[data-go]");
      if (g) { goSec(g.dataset.go); return; }
      if (e.target.closest("a, button") || performance.now() - swiped < 400 || String(getSelection() || "").length) return;
      const r = stage.getBoundingClientRect(), x = e.clientX;
      if (x < r.left + r.width * .4) next(); else if (x > r.right - r.width * .4) prev();
    });
    rd.querySelector(".rd-ctrl .nx").onclick = next;
    rd.querySelector(".rd-ctrl .pv").onclick = prev;
    const resize = d => { const s2 = Math.max(0, Math.min(SIZES.length - 1, size + d)); if (s2 === size) return; size = s2; store.set(KEY_SIZE, size); layout(); };
    rd.querySelector(".rd-size .sm").onclick = () => resize(-1);
    rd.querySelector(".rd-size .lg").onclick = () => resize(1);
    const openToc = () => { tocp.hidden = false; const h = tocp.querySelector("a.here"); if (h) h.scrollIntoView({ block: "center" }); tocp.querySelector(".close").focus(); };
    const closeToc = () => { tocp.hidden = true; rd.querySelector(".open-toc").focus(); };
    rd.querySelector(".open-toc").onclick = openToc;
    tocp.querySelector(".close").onclick = closeToc;
    tocp.addEventListener("click", e => { const g = e.target.closest("[data-go]"); if (g) { closeToc(); goSec(g.dataset.go); } });
    win.addEventListener("scroll", () => { win.scrollLeft = 0; win.scrollTop = 0; });
    let rz = 0;
    const onResize = () => { cancelAnimationFrame(rz); rz = requestAnimationFrame(() => { if (secs.length) layout(); }); };
    addEventListener("keydown", onKey);
    addEventListener("resize", onResize);
    stage.addEventListener("wheel", onWheel, { passive: false });
    stage.addEventListener("touchstart", onStart, { passive: true });
    stage.addEventListener("touchend", onEnd, { passive: true });

    loadText().then(text => {
      if (!alive) return;
      secs = text;
      flow.innerHTML = bookHTML(secs);
      tocp.querySelector(".list").innerHTML = tocList(secs);
      layout();
      if (document.fonts && document.fonts.status !== "loaded") document.fonts.ready.then(() => { if (alive) layout(); });
    }, () => { count.textContent = ""; flow.innerHTML = `<p>לא הצלחתי לטעון את הטקסט. אפשר לנסות לרענן את הדף.</p>`; });

    active = () => {
      alive = false;
      removeEventListener("keydown", onKey);
      removeEventListener("resize", onResize);
      document.documentElement.classList.remove("kt-lock");
      if (bar) bar.style.transform = "scaleX(0)";
      active = null;
    };
  }

  B.register({
    id: "read", title: "קריאה רגילה", kind: "ספר", accent: "#c48b90",
    mount: root => mount(root), unmount: () => { if (active) active(); }
  });
})();
